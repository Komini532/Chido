namespace Chido.Data.Locking;

/// <summary>
/// 悲観ロックのアンカー（戦闘システム 7.1・7.2）。
///
/// ロック対象を個別テーブルごとに列挙するのではなく、<b>必ず行が存在する実体テーブルの1行を
/// アンカーとして取得する</b>方式に統一している。「行が存在しないこと」をロックで守ろうとすると
/// InnoDB のギャップロックに依存することになり、ギャップロックは <c>REPEATABLE READ</c> でのみ
/// 機能するため、<c>READ COMMITTED</c> に切り替えた瞬間にエラーも警告もなく排他が消滅する。
/// 常に行が存在するテーブルをアンカーにすれば、トランザクション分離レベルに依存しない。
///
/// <b>値の大小がそのまま正準ロック順序である。</b>デッドロックを構造的に排除するため
/// 取得順序をこの並びに固定し、<see cref="BattleLock"/> が違反を実行時に弾く。
/// </summary>
public enum LockAnchor
{
    /// <summary>
    /// プレイヤー行（<c>chido_player.user_id</c>／行動者本人）。
    /// </summary>
    Player = 1,

    /// <summary>
    /// チャンネル行（<c>chido_channel_state.channel_id</c>）。
    ///
    /// <b>全戦闘行動の直列化点。</b>これを保持している間は「1チャンネルにアクティブなセッションは
    /// 1つ以下」が保証されるため、戦闘行動においてセッション行のロックは冗長になる。
    /// 参加者行・プレイヤーの装備スロット、および全参加者の <c>chido_player_effect</c> への
    /// 書き込みも本アンカーに包摂される。
    /// </summary>
    Channel = 2,

    /// <summary>
    /// セッション行（<c>chido_battle_session.session_id</c>）。
    ///
    /// 必要になるのは、チャンネル行を取得しない非チャンネル起点コマンド（装備変更等）との排他のみ。
    /// </summary>
    Session = 3,
}
